// Real metro systems exist in Lucknow, Jaipur and Nagpur (as of this
// dataset); Indore, Coimbatore and Bhubaneswar do not yet have one.
const metroCities = new Set(["Lucknow", "Jaipur", "Nagpur"]);

const nearbyByCity = {
  Indore: { schools: ["Delhi Public School, Indore", "Choithram School"], hospitals: ["CHL Hospital", "Bombay Hospital Indore"] },
  Coimbatore: { schools: ["PSG Public School", "Chinmaya Vidyalaya"], hospitals: ["PSG Hospitals", "Kovai Medical Center"] },
  Nagpur: { schools: ["Somalwar High School", "St. Ursula Girls' High School"], hospitals: ["Wockhardt Hospital", "Orange City Hospital"] },
  Lucknow: { schools: ["City Montessori School", "La Martiniere College"], hospitals: ["Sahara Hospital", "Medanta Lucknow"] },
  Jaipur: { schools: ["Maharani Gayatri Devi School", "St. Xavier's School Jaipur"], hospitals: ["Fortis Escorts Jaipur", "Narayana Multispeciality Hospital"] },
  Bhubaneswar: { schools: ["DAV Public School, Chandrasekharpur", "Sai International School"], hospitals: ["AMRI Hospital Bhubaneswar", "Apollo Hospitals Bhubaneswar"] },
};

// Attach shared fields (image seeds, nearby info) deterministically.
export const properties = base.map((p, i) => {
  const nearby = nearbyByCity[p.city] || { schools: ["Local Public School"], hospitals: ["City Hospital"] };
  return {
    ...p,
    images: [1, 2, 3, 4].map((n) => `${p.id}-${n}`),
    nearby: {
      schools: nearby.schools[i % nearby.schools.length],
      hospitals: nearby.hospitals[i % nearby.hospitals.length],
      metro: metroCities.has(p.city) ? `${(0.5 + (i % 5) * 0.3).toFixed(1)} km` : null,
    },
  };
});

export function getPropertyById(id) {
  return properties.find((p) => p.id === id);
}

export function getSimilarProperties(property, count = 4) {
  return properties
    .filter(
      (p) =>
        p.id !== property.id &&
        p.category === property.category &&
        (p.city === property.city || p.type === property.type)
    )
    .slice(0, count);
}
