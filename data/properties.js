export function getPropertyById(id) {
  return properties.find((p) => p.id === id);
}

export function getSimilarProperties(property, count = 4) {
  return properties
    .filter(
      (p) =>
        p.id !== property.id &&
        p.category === property.category &&
        (p.city === property.city || p.type === property.type)
    )
    .slice(0, count);
}
